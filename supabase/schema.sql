-- ---------- ad_spend (mapped to a model) ----------
create table public.ad_spend (
  id bigint generated always as identity primary key,
  date date not null,
  ad_id text,
  adset_id text not null,
  adset_name text,
  model_group_id bigint references public.model_groups(id),
  spend numeric(12,2) not null,
  currency text default 'EGP',
  -- traffic source the spend came from ('meta' | 'tiktok'); splits the P&L
  -- ad-spend line (see src/lib/reports/daily-pnl.ts, src/lib/tiktok-spend.ts).
  source text not null default 'meta',
  synced_at timestamptz not null default now(),
  unique (date, adset_id, ad_id)
);

-- ---------- monthly_delivery_rates (store-wide, per calendar month) ----------
create table public.monthly_delivery_rates (
  month date primary key,
  resolved_count int not null,
  delivered_count int not null,
  rate numeric(6,4) not null,
  computed_at timestamptz not null default now()
);

-- ---------- sku_monthly_delivery_rates (per product, per month) ----------
create table public.sku_monthly_delivery_rates (
  product_id bigint not null references public.products(id),
  month date not null,
  resolved_count int not null,
  delivered_count int not null,
  rate numeric(6,4) not null,
  created_at timestamptz not null default now(),
  primary key (product_id, month)
);

