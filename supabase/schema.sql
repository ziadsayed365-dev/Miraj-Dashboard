drop schema if exists public cascade;
create schema public;

-- ---------- model_groups (a "model" above individual color products) ----------
create table public.model_groups (
  id bigint generated always as identity primary key,
  name text not null,
  unit_cost numeric(12,2),
  refund_rate_override numeric(6,4),
  damage_rate_override numeric(6,4),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- products (one row per Shopify product / color) ----------
create table public.products (
  id bigint generated always as identity primary key,
  shopify_product_id bigint unique,
  name text not null,
  sku text,
  model_group_id bigint references public.model_groups(id),
  current_price numeric(12,2),
  price_synced_at timestamptz,
  unit_cost_override numeric(12,2),
  status text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- orders ----------
create table public.orders (
  id bigint generated always as identity primary key,
  shopify_order_id bigint unique not null,
  order_number text not null,
  order_created_at timestamptz not null,
  egypt_day date not null,
  total_price numeric(12,2),
  currency text default 'EGP',
  governorate_shopify text,
  cancelled_at timestamptz,
  financial_status text,
  shipping_fee_charged numeric(12,2),

  bosta_tracking_number text,
  outcome text check (outcome in ('in_transit','delivered','failed_rto','exchange','pickup_return','cancelled_return')),
  outcome_governorate text,
  attempt_number int default 1,
  cod_amount_collected numeric(12,2),
  resolved_at timestamptz,
  stock_received_at timestamptz,
  last_bosta_sync_at timestamptz,
  bosta_picked_up_day date,

  courier text check (courier in ('bosta', 'movers')),
  movers_record_date date,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index orders_egypt_day_idx on public.orders (egypt_day);
create index orders_order_number_idx on public.orders (order_number);
create index orders_bosta_picked_up_day_idx on public.orders (bosta_picked_up_day);

-- ---------- order_line_items ----------
create table public.order_line_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id),
  shopify_line_item_id bigint,
  shopify_product_id bigint,
  product_title_raw text,
  quantity int not null check (quantity > 0),
  unit_price numeric(12,2) not null,

  -- valuation engine outputs
  revenue numeric(12,2),
  cost_of_goods numeric(12,2),
  allocated_courier_fee numeric(12,2),
  allocated_cod_cash_fee numeric(12,2),
  allocated_open_package_fee numeric(12,2),
  packing_cost numeric(12,2),
  refund_adjustment numeric(12,2),
  damage_adjustment numeric(12,2),
  success_rate_used numeric(6,4),
  expected_margin numeric(12,2),
  realized_margin numeric(12,2),
  fee_breakdown jsonb,
  margin_computed_at timestamptz,

  created_at timestamptz not null default now()
);
create index order_line_items_order_id_idx on public.order_line_items (order_id);
create index order_line_items_product_id_idx on public.order_line_items (product_id);
create unique index order_line_items_shopify_line_item_id_key
  on public.order_line_items (shopify_line_item_id);

-- ---------- bosta_events (append-only courier audit trail) ----------
create table public.bosta_events (
  id bigint generated always as identity primary key,
  order_id bigint references public.orders(id),
  bosta_delivery_id text not null,
  business_reference text,
  bosta_type text,
  bosta_state text,
  attempt_number int,
  cod_amount numeric(12,2),
  governorate text,
  event_timestamp timestamptz,
  raw_payload jsonb,
  synced_at timestamptz not null default now()
);
create index bosta_events_order_id_idx on public.bosta_events (order_id);
create unique index bosta_events_delivery_id_key on public.bosta_events (bosta_delivery_id);

